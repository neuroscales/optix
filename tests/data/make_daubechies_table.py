"""Generate `src/optix/destripe/_daubechies.py` (needs `mpmath`).

The Daubechies filters dbN (N = 1, ..., 45, the range of Matlab's `dbN`)
are built by spectral factorisation (Daubechies 1992, Section 6.1), in
120-digit arithmetic:

    P(y) = ∑ₖ₌₀^{N−1} C(N−1+k, k)·yᵏ,  y = sin²(ω/2),

each root y of P gives the pair z + 1/z = 2 − 4y, of which the root
inside the unit circle is kept (minimum phase), and

    h(z) ∝ (1 + z)ᴺ · ∏ (z − zₖ),  ∑ h = √2.

The coefficients are printed with 17 significant digits (exact to float64
rounding); they match PyWavelets' `rec_lo` (db1-db38).

```text
python tests/data/make_daubechies_table.py > src/optix/destripe/_daubechies.py
```
"""

import mpmath

DPS = 120
NMAX = 45


def daubechies(n: int) -> list:
    mpmath.mp.dps = DPS
    h = [mpmath.mpc(1)]
    if n > 1:
        c = [mpmath.binomial(n - 1 + k, k) for k in range(n)]
        for y in mpmath.polyroots(c[::-1], maxsteps=2000, extraprec=4 * DPS):
            b = 2 - 4 * y
            z = (b + mpmath.sqrt(b * b - 4)) / 2
            z = z if abs(z) < 1 else 1 / z
            h = [
                (h[i] if i < len(h) else 0) - z * (h[i - 1] if i else 0)
                for i in range(len(h) + 1)
            ]
    for _ in range(n):
        h = [
            (h[i] if i < len(h) else 0) + (h[i - 1] if i else 0)
            for i in range(len(h) + 1)
        ]
    h = [mpmath.re(v) for v in h]
    s = sum(h)
    return [v * mpmath.sqrt(2) / s for v in h]


def main() -> None:
    print('"""Daubechies scaling filters db1-db45 (generated; do not edit).')
    print()
    print("Generated by `tests/data/make_daubechies_table.py`. Entry N − 1")
    print("holds the reconstruction low-pass filter of dbN, length 2N.")
    print('"""')
    print()
    print("DAUBECHIES = (")
    for n in range(1, NMAX + 1):
        values = [
            mpmath.nstr(v, 17, min_fixed=-1, max_fixed=1)
            for v in daubechies(n)
        ]
        print(f"    # db{n}")
        print("    (")
        for v in values:
            print(f"        {v},")
        print("    ),")
    print(")")


if __name__ == "__main__":
    main()
